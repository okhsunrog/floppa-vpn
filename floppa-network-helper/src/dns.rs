use crate::{
    Context as Helper,
    journal::{Fingerprint, Record, Resolver, atomic_write, sync_dir},
};
use anyhow::{Context, Result, bail, ensure};
use sha2::{Digest, Sha256};
use std::{
    fs::{self, OpenOptions},
    io::{Read, Write},
    os::unix::fs::{MetadataExt, OpenOptionsExt, PermissionsExt, symlink},
    path::Path,
};
const RESOLVER: &str = "/etc/resolv.conf";
const MAX: u64 = 262_144;
fn fingerprint(path: &Path) -> Result<Fingerprint> {
    let mut f = OpenOptions::new()
        .read(true)
        .custom_flags(libc::O_NOFOLLOW | libc::O_NONBLOCK)
        .open(path)?;
    let m = f.metadata()?;
    ensure!(m.is_file() && m.len() <= MAX, "invalid resolver file");
    let mut bytes = Vec::new();
    (&mut f).take(MAX + 1).read_to_end(&mut bytes)?;
    ensure!(bytes.len() as u64 <= MAX, "oversized resolver");
    Ok(Fingerprint {
        device: m.dev(),
        inode: m.ino(),
        sha256: format!("{:x}", Sha256::digest(&bytes)),
    })
}
fn snapshot() -> Result<Resolver> {
    match fs::symlink_metadata(RESOLVER) {
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Resolver::Absent),
        Err(e) => Err(e.into()),
        Ok(m) if m.file_type().is_symlink() => Ok(Resolver::Link {
            target: fs::read_link(RESOLVER)?,
        }),
        Ok(m) if m.is_file() && m.len() <= MAX => {
            fingerprint(Path::new(RESOLVER))?;
            Ok(Resolver::File {
                bytes: fs::read(RESOLVER)?,
            })
        }
        _ => bail!("resolver is not a regular file or symlink"),
    }
}
impl Helper {
    fn resolved_owns_dns(&self) -> Result<bool> {
        let content = match fs::read_to_string(RESOLVER) {
            Ok(s) => s,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(false),
            Err(e) => return Err(e).context("read system resolver"),
        };
        let mut seen = false;
        for line in content.lines() {
            let mut words = line.split_whitespace();
            if words.next() != Some("nameserver") {
                continue;
            }
            seen = true;
            if !matches!(words.next(), Some("127.0.0.53" | "127.0.0.54")) {
                return Ok(false);
            }
        }
        if !seen {
            return Ok(false);
        }
        // If the system points at resolved but it cannot be reached, fail visibly. Replacing
        // its stub on an API error would silently switch DNS managers during a service restart.
        self.cmd.run("resolvectl", &["status"], None)?;
        Ok(true)
    }
    pub fn set_dns_auto(&self, iface: &str, servers: &[String]) -> Result<()> {
        if self.resolved_owns_dns()? {
            self.set_dns(iface, servers)
        } else {
            self.set_dns_file(servers)
        }
    }
    pub fn set_dns(&self, iface: &str, servers: &[String]) -> Result<()> {
        let index = self.index(iface)?;
        self.journal.save(
            "dns",
            Record::Resolved {
                boot: self.boot.clone(),
                iface: iface.into(),
                index: Some(index),
            },
        )?;
        crate::checkpoint("dns-saved");
        let mut args = vec!["dns", iface];
        args.extend(servers.iter().map(String::as_str));
        self.cmd.run("resolvectl", &args, None)?;
        crate::checkpoint("dns-servers");
        self.cmd.run("resolvectl", &["domain", iface, "~."], None)?;
        crate::checkpoint("dns-domain");
        self.cmd
            .run("resolvectl", &["default-route", iface, "true"], None)?;
        Ok(())
    }
    pub fn set_dns_file(&self, servers: &[String]) -> Result<()> {
        ensure!(self.journal.load("dns")?.is_none(), "pending DNS recovery");
        let original = snapshot()?;
        let mut tmp = tempfile::Builder::new()
            .prefix(".floppa-resolv-")
            .tempfile_in("/etc")?;
        tmp.as_file()
            .set_permissions(fs::Permissions::from_mode(0o644))?;
        writeln!(tmp, "# Generated by floppa-vpn")?;
        for server in servers {
            writeln!(tmp, "nameserver {server}")?;
        }
        tmp.as_file().sync_all()?;
        let installed = fingerprint(tmp.path())?;
        self.journal.save(
            "dns",
            Record::FileDns {
                original,
                installed: Some(installed),
            },
        )?;
        crate::checkpoint("dns-saved");
        tmp.persist(RESOLVER).map_err(|e| e.error)?;
        sync_dir(Path::new("/etc"))?;
        crate::checkpoint("dns-installed");
        Ok(())
    }
    pub fn recover_dns(&self) -> Result<()> {
        let Some(record) = self.journal.load("dns")? else {
            return Ok(());
        };
        match record {
            Record::Resolved { boot, iface, index } => {
                if boot == self.boot && self.link(&iface)?.is_some() {
                    // A replacement link has no DNS state belonging to the previous tunnel.
                    if index.is_none() || Some(self.index(&iface)?) == index {
                        self.cmd.run("resolvectl", &["revert", &iface], None)?;
                    }
                }
            }
            Record::FileDns {
                original,
                installed,
            } => {
                let owned = match fs::symlink_metadata(RESOLVER) {
                    Err(e) if e.kind() == std::io::ErrorKind::NotFound => false,
                    Err(e) => return Err(e.into()),
                    Ok(m) if m.is_dir() => {
                        bail!("resolver is a directory; keeping recovery record")
                    }
                    Ok(m) if m.is_file() => {
                        if let Some(expected) = installed {
                            fingerprint(Path::new(RESOLVER))? == expected
                        } else {
                            fs::read_to_string(RESOLVER)?.lines().next()
                                == Some("# Generated by floppa-vpn")
                        }
                    }
                    Ok(_) => false,
                };
                if owned {
                    match original {
                        Resolver::Absent => {
                            fs::remove_file(RESOLVER)?;
                            sync_dir(Path::new("/etc"))?;
                        }
                        Resolver::File { bytes } => {
                            atomic_write(Path::new(RESOLVER), &bytes, 0o644)?
                        }
                        Resolver::Link { target } => {
                            // Stage inside a private directory, then atomically rename over the
                            // installed file. No unlink/install gap if recovery itself is killed.
                            let dir = tempfile::Builder::new()
                                .prefix(".floppa-link-")
                                .tempdir_in("/etc")?;
                            let link = dir.path().join("resolv.conf");
                            symlink(target, &link)?;
                            sync_dir(dir.path())?;
                            fs::rename(link, RESOLVER)?;
                            sync_dir(Path::new("/etc"))?;
                        }
                    }
                } else {
                    eprintln!(
                        "Resolver changed externally or installation did not complete; preserving current DNS"
                    );
                }
            }
            _ => bail!("wrong DNS record"),
        }
        crate::checkpoint("dns-restored");
        self.journal.clear("dns")
    }
}
